/**
 * refactorSimulator.js
 * In-memory "What-If" Architecture Refactoring Simulator.
 * Dynamically tests the impact of cutting dependency edges,
 * re-evaluating cycles and calculating the health score boost.
 */

import { calculateHealthScore } from './healthCalculator';

function detectCyclesInEdges(nodes, edges) {
  const adj = new Map();
  nodes.forEach(n => adj.set(n.id, []));
  edges.forEach(e => {
    if (adj.has(e.source)) {
      adj.get(e.source).push(e.target);
    }
  });

  const visited = new Set();
  const recStack = new Set();
  const cycles = [];

  function dfs(curr, path) {
    visited.add(curr);
    recStack.add(curr);

    const neighbors = adj.get(curr) || [];
    for (const neighbor of neighbors) {
      if (!visited.has(neighbor)) {
        dfs(neighbor, [...path, neighbor]);
      } else if (recStack.has(neighbor)) {
        // Cycle detected
        const cycleStartIndex = path.indexOf(neighbor);
        if (cycleStartIndex !== -1) {
          const cyclePath = path.slice(cycleStartIndex);
          cycles.push([...cyclePath, neighbor]);
        }
      }
    }

    recStack.delete(curr);
  }

  nodes.forEach(n => {
    if (!visited.has(n.id)) {
      dfs(n.id, [n.id]);
    }
  });

  return cycles;
}

export function simulateRefactoring(repository, cutEdgeKeys = new Set()) {
  if (!repository) return null;

  const nodes = repository.nodes || [];
  const originalEdges = repository.edges || [];

  // Filter out edges that were cut in the simulator
  const simulatedEdges = originalEdges.filter(e => {
    const key = `${e.source}|${e.target}`;
    return !cutEdgeKeys.has(key);
  });

  // Re-detect cycles with simulated edges
  const simulatedCycles = detectCyclesInEdges(nodes, simulatedEdges);

  // Compute baseline health vs simulated health
  const baselineHealth = calculateHealthScore(repository);

  // Create simulated repo mock for health calculation
  const simulatedRepoMock = {
    ...repository,
    edges: simulatedEdges,
    summary: {
      ...repository.summary,
      internalEdgesCount: simulatedEdges.length,
      cycleCount: simulatedCycles.length
    },
    cycles: simulatedCycles
  };

  const simulatedHealth = calculateHealthScore(simulatedRepoMock);
  const scoreDelta = simulatedHealth.score - baselineHealth.score;
  const cyclesEliminated = Math.max(0, (repository.summary?.cycleCount || repository.cycles?.length || 0) - simulatedCycles.length);

  return {
    cutEdgeCount: cutEdgeKeys.size,
    baselineHealth,
    simulatedHealth,
    scoreDelta,
    cyclesEliminated,
    remainingCyclesCount: simulatedCycles.length,
    simulatedEdgesCount: simulatedEdges.length
  };
}

export function generateRefactoringPlanMarkdown(repository, cutEdgesList, simulationResult) {
  const repoName = repository?.name || 'Repository';
  const baseline = simulationResult.baselineHealth;
  const sim = simulationResult.simulatedHealth;

  return `# 🏗️ Architectural Refactoring Action Plan: ${repoName}

## 📊 Simulated Impact
* **Initial Health Grade**: Grade ${baseline.grade} (${baseline.score}/100)
* **Simulated Health Grade**: **Grade ${sim.grade} (${sim.score}/100)** (${simulationResult.scoreDelta >= 0 ? '+' : ''}${simulationResult.scoreDelta} pts)
* **Circular Loops Eliminated**: **${simulationResult.cyclesEliminated}** circular dependency loop(s)
* **Remaining Internal Connections**: ${simulationResult.simulatedEdgesCount} edges

---

## ✂️ Proposed Decoupling Tasks
${cutEdgesList.map((edge, idx) => `### ${idx + 1}. Decouple \`${edge.sourceLabel || edge.source}\` ➔ \`${edge.targetLabel || edge.target}\`
- **File**: \`${edge.source}\`
- **Import to Refactor**: \`${edge.target}\`
- **Strategy**:
  - [ ] Extract shared types/interfaces into a pure boundary or contract file.
  - [ ] Invert dependency by injecting service instance through constructor or parameter.
  - [ ] Replace synchronous module import with event emission or asynchronous boundary.
`).join('\n')}

---
*Generated by RepoRadar Architecture Refactoring Simulator*
`;
}
