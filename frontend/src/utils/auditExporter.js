import { calculateHealthScore } from './healthCalculator';

/**
 * Downloads a file to the user's browser
 */
function downloadFile(filename, content, mimeType = 'text/plain') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Exports complete Architectural Audit Report as Markdown
 */
export function downloadMarkdownAudit(repo) {
  if (!repo) return;

  const health = calculateHealthScore(repo);
  const repoName = repo.name || 'repository';
  const owner = repo.owner || 'unknown';
  const timestamp = new Date().toISOString().split('T')[0];

  const languagesList = repo.languages?.length
    ? repo.languages.map(l => `| ${l.name} | ${l.count} files | ${l.percentage}% |`).join('\n')
    : '| JavaScript | - | 100% |';

  const topImportedFiles = [...(repo.files || [])]
    .sort((a, b) => (b.inDegree || 0) - (a.inDegree || 0))
    .slice(0, 5);

  const topImportedTable = topImportedFiles.length
    ? topImportedFiles
        .map(
          (f, idx) =>
            `| ${idx + 1} | \`${f.path}\` | **${f.inDegree || 0} callers** | ${f.outDegree || 0} imports | ${f.language} |`
        )
        .join('\n')
    : '| 1 | None | 0 | 0 | - |';

  const cyclesSection =
    repo.cycles && repo.cycles.length > 0
      ? repo.cycles
          .map(
            (c, i) =>
              `### Loop #${i + 1}\n\`\`\`text\n${c.join(' -> ')} -> ${c[0]}\n\`\`\``
          )
          .join('\n\n')
      : '✅ **Zero Circular Dependencies Detected.** The codebase forms a clean Directed Acyclic Graph (DAG).';

  const externalPackagesList = repo.externalPackages?.length
    ? repo.externalPackages.map(pkg => `- \`${pkg}\``).join('\n')
    : '_No external package dependencies identified._';

  const markdownContent = `# Architectural Audit Report: ${owner}/${repoName}
> Generated by **RepoRadar — Codebase Cartography** on ${timestamp}

---

## 🛡️ Executive Summary & Health Grade

| Architectural Metric | Value | Status / Notes |
|---|---|---|
| **Architectural Health Score** | **${health.score} / 100** | Grade: **${health.grade}** |
| **Coupling Density** | **${health.density} edges/file** | Average dependencies per file |
| **Circular Dependency Loops** | **${repo.summary?.cycleCount || 0} cycles** | ${repo.summary?.cycleCount === 0 ? 'Optimal' : 'Needs attention'} |
| **Analyzed Source Files** | **${repo.summary?.analyzedFilesCount || 0}** | Filtered JS/TS source modules |
| **Internal Dependency Edges** | **${repo.summary?.internalEdgesCount || 0}** | AST-derived import connections |
| **External NPM Packages** | **${repo.summary?.externalPackagesCount || 0}** | 3rd-party library dependencies |

### Key Architectural Findings
${health.insights.map(item => `- **${item.type.toUpperCase()}**: ${item.text}`).join('\n')}

---

## 📊 Language Distribution
| Language | File Count | Percentage |
|---|---|---|
${languagesList}

---

## 🎯 Top 5 Critical Hub Files (Highest In-Degree / Ripple Impact)
These files are imported most frequently across the repository. Refactoring these files carries the highest blast radius:

| Rank | File Path | Direct Callers (In-Degree) | Outgoing Imports | Language |
|---|---|---|---|---|
${topImportedTable}

---

## 🔄 Circular Dependency Risk Analysis
Circular dependencies increase modular coupling and can cause bundler execution loops:

${cyclesSection}

---

## 📦 External NPM Package Dependencies (${repo.externalPackages?.length || 0} packages)
The codebase depends on the following external libraries:

${externalPackagesList}

---

*Report automatically compiled and generated with [RepoRadar](https://github.com/your-username/RepoRadar).*
`;

  downloadFile(`ARCHITECTURAL_AUDIT_${owner}_${repoName}.md`, markdownContent, 'text/markdown');
}

/**
 * Exports Raw Graph JSON for CI/CD or data analysis
 */
export function downloadJsonGraph(repo) {
  if (!repo) return;

  const exportPayload = {
    repository: {
      owner: repo.owner,
      name: repo.name,
      url: repo.url,
      analyzedAt: repo.analyzedAt,
      summary: repo.summary
    },
    graph: {
      nodes: repo.nodes || [],
      edges: repo.edges || [],
      cycles: repo.cycles || []
    },
    files: (repo.files || []).map(f => ({
      path: f.path,
      language: f.language,
      inDegree: f.inDegree,
      outDegree: f.outDegree,
      imports: f.imports,
      externalImports: f.externalImports
    })),
    externalPackages: repo.externalPackages || []
  };

  const jsonContent = JSON.stringify(exportPayload, null, 2);
  downloadFile(`reporadar_${repo.owner}_${repo.name}_graph.json`, jsonContent, 'application/json');
}
