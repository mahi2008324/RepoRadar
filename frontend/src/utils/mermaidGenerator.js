/**
 * mermaidGenerator.js
 * Generates copy-pasteable Mermaid.js architecture diagrams and
 * Shields.io README badges for any analyzed GitHub repository.
 */

export function generateMermaidDiagram(repository, maxNodes = 35) {
  if (!repository) return '';

  const nodes = repository.nodes || [];
  const edges = repository.edges || [];

  if (nodes.length === 0) {
    return 'graph TD\n  Empty["No internal source nodes detected"]';
  }

  // Filter top connected nodes if too large for clean README rendering
  const degreeMap = new Map();
  nodes.forEach(n => degreeMap.set(n.id, 0));
  edges.forEach(e => {
    degreeMap.set(e.source, (degreeMap.get(e.source) || 0) + 1);
    degreeMap.set(e.target, (degreeMap.get(e.target) || 0) + 1);
  });

  const topNodes = [...nodes]
    .sort((a, b) => (degreeMap.get(b.id) || 0) - (degreeMap.get(a.id) || 0))
    .slice(0, maxNodes);

  const topNodeIdSet = new Set(topNodes.map(n => n.id));
  const relevantEdges = edges.filter(
    e => topNodeIdSet.has(e.source) && topNodeIdSet.has(e.target)
  );

  // Group nodes by directory for subgraphs
  const directoryGroups = new Map();
  topNodes.forEach(node => {
    const path = node.path || node.label || node.id;
    const parts = path.split('/');
    const dir = parts.length > 1 ? parts.slice(0, -1).join('/') : 'root';
    if (!directoryGroups.has(dir)) {
      directoryGroups.set(dir, []);
    }
    directoryGroups.get(dir).push(node);
  });

  const sanitizeId = (id) => {
    return 'node_' + id.replace(/[^a-zA-Z0-9_]/g, '_');
  };

  const sanitizeSubId = (id) => {
    return 'sub_' + id.replace(/[^a-zA-Z0-9_]/g, '_');
  };

  let mermaid = '```mermaid\n';
  mermaid += 'graph TD\n';
  mermaid += '  %% Auto-generated by RepoRadar Architecture Mapper\n\n';

  // Output Subgraphs
  directoryGroups.forEach((groupNodes, dirName) => {
    mermaid += `  subgraph ${sanitizeSubId(dirName)} ["📁 ${dirName}"]\n`;
    groupNodes.forEach(n => {
      const label = (n.path || n.label || n.id).split('/').pop();
      mermaid += `    ${sanitizeId(n.id)}["${label}"]\n`;
    });
    mermaid += '  end\n\n';
  });

  // Output Directed Edges
  relevantEdges.forEach(e => {
    mermaid += `  ${sanitizeId(e.source)} --> ${sanitizeId(e.target)}\n`;
  });

  // Add styles
  mermaid += '\n  classDef default fill:#1e293b,stroke:#475569,stroke-width:1px,color:#f8fafc;\n';
  mermaid += '```';

  return mermaid;
}

export function generateReadmeBadges(repository, health) {
  if (!repository) return '';

  const owner = repository.owner || 'owner';
  const name = repository.name || 'repository';
  const score = health?.score || 90;
  const grade = health?.grade || 'A';
  const cycleCount = repository.summary?.cycleCount || 0;

  // Grade color mapping for shields.io
  let gradeColor = '10b981'; // Green
  if (score < 60) gradeColor = 'ef4444'; // Red
  else if (score < 75) gradeColor = 'f59e0b'; // Amber
  else if (score < 85) gradeColor = '06b6d4'; // Cyan

  const badges = [
    {
      title: 'Architecture Health',
      markdown: `[![RepoRadar Health](https://img.shields.io/badge/RepoRadar_Health-${grade}_(${score}%2F100)-${gradeColor}?style=for-the-badge&logo=shield)](http://localhost:5173/repositories/${repository.id})`,
      previewUrl: `https://img.shields.io/badge/RepoRadar_Health-${grade}_(${score}%2F100)-${gradeColor}?style=for-the-badge&logo=shield`
    },
    {
      title: 'Circular Cycles',
      markdown: `[![Circular Dependencies](https://img.shields.io/badge/Circular_Loops-${cycleCount}_detected-${cycleCount === 0 ? '10b981' : 'ef4444'}?style=for-the-badge&logo=git)](http://localhost:5173/repositories/${repository.id}/analysis)`,
      previewUrl: `https://img.shields.io/badge/Circular_Loops-${cycleCount}_detected-${cycleCount === 0 ? '10b981' : 'ef4444'}?style=for-the-badge&logo=git`
    },
    {
      title: 'Architecture Verified',
      markdown: `[![RepoRadar Verified](https://img.shields.io/badge/Architecture-Mapped_by_RepoRadar-6366f1?style=for-the-badge&logo=radar)](http://localhost:5173/repositories/${repository.id})`,
      previewUrl: `https://img.shields.io/badge/Architecture-Mapped_by_RepoRadar-6366f1?style=for-the-badge&logo=radar`
    }
  ];

  const fullMarkdownBundle = `<!-- RepoRadar Architecture Badges -->
${badges.map(b => b.markdown).join('\n')}
<!-- End RepoRadar Badges -->`;

  return { badges, fullMarkdownBundle };
}
